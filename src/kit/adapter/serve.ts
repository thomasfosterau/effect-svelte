/**
 * Production server entry for the Effect SvelteKit adapter.
 *
 * The adapter's generated `build/index.js` calls {@link serve} with the
 * handler from `build/handler.js`. The server runs on
 * `@effect/platform-node`'s `NodeHttpServer`, with configuration read from
 * the environment and graceful shutdown handled by Effect scopes.
 *
 * For full control (custom layers, tracing, additional routes), skip the
 * generated entry and compose {@link layer} — or the handler itself — into
 * your own Effect application.
 */

import { createServer } from "node:http";
import * as HttpMiddleware from "@effect/platform/HttpMiddleware";
import * as HttpServer from "@effect/platform/HttpServer";
import * as NodeHttpServer from "@effect/platform-node/NodeHttpServer";
import * as NodeRuntime from "@effect/platform-node/NodeRuntime";
import { Config, Effect, Layer } from "effect";
import type { SvelteKitHttpApp } from "./handler.js";

export interface ServeOptions {
  /** Prefix for the configuration environment variables (PORT, HOST, ...). */
  readonly envPrefix?: string;
  /**
   * Additional layer merged into the server context, e.g. tracing or logging
   * layers.
   */
  readonly layer?: Layer.Layer<never, never>;
  /**
   * Disable the default request logger middleware.
   */
  readonly disableLogger?: boolean;
}

/**
 * Builds the full server layer for a SvelteKit HttpApp: HTTP listener
 * (`PORT` / `HOST` environment variables), request logging, and the
 * platform services the handler needs.
 *
 * Launch it with `Layer.launch`, or merge it into a larger application.
 */
export const layer = (
  handler: Effect.Effect<SvelteKitHttpApp, never, NodeHttpServerServices>,
  options: ServeOptions = {},
): Layer.Layer<never, unknown> => {
  const prefix = options.envPrefix ?? "";

  const serveLayer = Layer.unwrapEffect(
    Effect.map(handler, (app) =>
      options.disableLogger ? HttpServer.serve(app) : HttpServer.serve(app, HttpMiddleware.logger),
    ),
  );

  const listenLayer = NodeHttpServer.layerConfig(createServer, {
    port: Config.integer(`${prefix}PORT`).pipe(Config.withDefault(3000)),
    host: Config.string(`${prefix}HOST`).pipe(Config.withDefault("0.0.0.0")),
  });

  const withListener = serveLayer.pipe(HttpServer.withLogAddress, Layer.provide(listenLayer));

  return options.layer ? Layer.merge(withListener, options.layer) : withListener;
};

/** The services provided to the handler effect by `NodeHttpServer.layerConfig`. */
type NodeHttpServerServices = Layer.Layer.Success<ReturnType<typeof NodeHttpServer.layerConfig>>;

/**
 * Starts the production server and runs it until the process receives
 * SIGINT/SIGTERM, at which point the server (and every Effect resource) is
 * shut down gracefully.
 *
 * @example
 * ```ts
 * // build/index.js (generated by the adapter)
 * import { handler } from "./handler.js";
 * import { serve } from "@thomasfosterau/effect-svelte/kit/adapter/serve";
 *
 * serve(handler);
 * ```
 */
export const serve = (
  handler: Effect.Effect<SvelteKitHttpApp, never, NodeHttpServerServices>,
  options: ServeOptions = {},
): void => {
  NodeRuntime.runMain(Layer.launch(layer(handler, options)));
};
